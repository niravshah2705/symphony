NOTE = "# Generated by AI Fleet — review before use. Pin digests for production."


def json_exec(cmd) -> str:
    """Render a command string as a JSON exec-form array for CMD/ENTRYPOINT."""
    parts = [p for p in re.split(r"\s+", str(cmd).strip()) if p]
    return json.dumps(parts if parts else ["true"], separators=(",", ":"))


def _node_template(spec):
    version = spec.get("version") or "20.18.1-bookworm-slim"
    port = spec.get("port") or 3000
    start = spec.get("start") or "node server.js"
    return "\n".join(
        [
            NOTE,
            f"FROM node:{version}",
            "ENV NODE_ENV=production",
            "WORKDIR /app",
            "COPY --chown=node:node package*.json ./",
            "RUN npm ci --omit=dev",
            "COPY --chown=node:node . .",
            "USER node",
            f"EXPOSE {port}",
            f"CMD {json_exec(start)}",
        ]
    )


