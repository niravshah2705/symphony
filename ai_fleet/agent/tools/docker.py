def render_dockerfile(spec=None) -> str:
    """Build a hardened Dockerfile for a language preset."""
    spec = spec or {}
    language = str(spec.get("language") or "generic").lower()
    build = TEMPLATES.get(language, TEMPLATES["generic"])
    return f"{build(spec)}\n"


def render_dockerignore() -> str:
    """Build a .dockerignore that keeps secrets and cruft out of the build context."""
    return "\n".join(
        [
            ".git",
            ".gitignore",
            "node_modules",
            "npm-debug.log",
            "**/__pycache__",
            "*.pyc",
            ".venv",
            "venv",
            "dist",
            "build",
            "target",
            ".env",
            ".env.*",
            "*.pem",
            "*.key",
            "id_rsa",
            ".aws",
            ".ssh",
            "secrets",
            "Dockerfile",
            ".dockerignore",
            "",
        ]
    )


IMAGE_RE = re.compile(r"^[A-Za-z0-9][\w./:@-]{0,220}$", re.ASCII)
NAME_RE = re.compile(r"^[A-Za-z0-9][\w.-]{0,127}$", re.ASCII)
PORT_RE = re.compile(r"^\d{1,5}(:\d{1,5})?(/(tcp|udp))?$")
ENV_NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def assert_image(ref):
    value = str(ref or "").strip()
    if not IMAGE_RE.match(value):
        raise Exception(f'invalid image reference: "{ref}"')
    return value


def assert_safe_volume(spec, base):
    """Reject host-filesystem and docker-socket bind mounts; allow named/workspace binds only."""
    value = str(spec or "").strip()
    pieces = value.split(":")
    source = pieces[0] if len(pieces) > 0 else ""
    dest = pieces[1] if len(pieces) > 1 else None
    rest = pieces[2:]
    if not source or not dest or len(rest) > 1:
        raise Exception(f'invalid volume "{spec}" (use source:container[:ro])')
    if re.search(r"docker\.sock", value, re.IGNORECASE):
        raise Exception("refusing to mount the Docker socket")
    if os.path.isabs(source):
        rel = os.path.relpath(os.path.abspath(source), base)
        if rel == ".." or rel.startswith(".." + os.sep) or os.path.isabs(rel):
            raise Exception(f'refusing host bind mount outside the workspace: "{source}"')
    return value


def port_args(ports=None):
    out = []
    for p in ports or []:
        v = str(p).strip()
        if not PORT_RE.match(v):
            raise Exception(f'invalid port mapping: "{p}"')
        out.extend(["-p", v])
    return out


def build_arg_pairs(map_=None):
    """--build-arg pairs, refusing secret-looking keys (they persist in image history)."""
    out = []
    for k, v in (map_ or {}).items():
        if not ENV_NAME_RE.match(k):
            raise Exception(f'invalid build-arg name: "{k}"')
        if SECRET_KEY_RE.search(k):
            raise Exception(
                f'refusing secret-looking build-arg "{k}" (it would persist in image layers; use BuildKit secrets)'
            )
        out.extend(["--build-arg", f"{k}={v}"])
    return out


def env_args(map_=None):
    out = []
    for k, v in (map_ or {}).items():
        if not ENV_NAME_RE.match(k):
            raise Exception(f'invalid env name: "{k}"')
        out.extend(["-e", f"{k}={v}"])
    return out


def assert_name(name):
    v = str(name or "").strip()
    if not NAME_RE.match(v):
        raise Exception(f'invalid container name: "{name}"')
    return v


def _rel_arg(ctx, rel):
    """Validate a workspace-relative path and return it unchanged for use as an arg."""
    resolve_workdir(ctx, rel)
    return rel


# ---- Schemas --------------------------------------------------------------


class _DockerfileGenerateSchema(BaseModel):
    language: Literal["node", "python", "go", "java", "generic"] = Field(description="runtime preset")
    version: Optional[str] = Field(default=None, description='base image tag, e.g. "20.18.1-bookworm-slim"')
    port: Optional[int] = Field(default=None, description="port to EXPOSE")
    start: Optional[str] = Field(default=None, description='start command, e.g. "node server.js"')
    dir: Optional[str] = Field(default=None, description="workspace-relative directory to write into (default: root)")


class _DockerBuildSchema(BaseModel):
    tag: str = Field(description='image tag, e.g. "myapp:dev"')
    dockerfile: Optional[str] = Field(default=None, description="workspace-relative Dockerfile path (default: ./Dockerfile)")
    context: Optional[str] = Field(default=None, description="workspace-relative build context (default: .)")
    buildArgs: Optional[Dict[str, str]] = Field(default=None, description="non-secret --build-arg values")


class _DockerRunSchema(BaseModel):
    image: str = Field(description="image reference to run")
    name: Optional[str] = Field(default=None, description="container name")
    ports: Optional[List[str]] = Field(default=None, description='port maps like "8080:80"')
    env: Optional[Dict[str, str]] = Field(default=None, description="environment variables for the container")
    volumes: Optional[List[str]] = Field(default=None, description='binds "src:container[:ro]" — host paths must stay inside the workspace')
    detach: Optional[bool] = Field(default=None, description="run detached (-d)")
    rm: Optional[bool] = Field(default=None, description="remove on exit (--rm), default true")
    command: Optional[List[str]] = Field(default=None, description="command + args to run in the container")


class _DockerComposeSchema(BaseModel):
    action: Literal["up", "down", "build", "ps", "logs"] = Field(description="compose subcommand")
    file: Optional[str] = Field(default=None, description="workspace-relative compose file (default: docker-compose.yml)")
    detach: Optional[bool] = Field(default=None, description='for "up": run detached (default true)')
    dir: Optional[str] = Field(default=None, description="workspace-relative project directory")


class _DockerInfoSchema(BaseModel):
    pass


# ---- Tool handlers --------------------------------------------------------


async def _dockerfile_generate(input, ctx):
    dir_ = resolve_workdir(ctx, input.get("dir"))
    os.makedirs(dir_, exist_ok=True)
    dockerfile = render_dockerfile(input)
    ignore_path = os.path.join(dir_, ".dockerignore")
    with open(os.path.join(dir_, "Dockerfile"), "w", encoding="utf-8") as f:
        f.write(dockerfile)
    if not os.path.exists(ignore_path):
        with open(ignore_path, "w", encoding="utf-8") as f:
            f.write(render_dockerignore())
    return f"✅ Wrote hardened Dockerfile + .dockerignore to {dir_}\n\n{dockerfile}"


async def _docker_build(input, ctx):
    tag = assert_image(input.get("tag"))
    args = ["build", "-t", tag, *build_arg_pairs(input.get("buildArgs"))]
    if input.get("dockerfile"):
        resolve_workdir(ctx, input["dockerfile"])
        args.extend(["-f", input["dockerfile"]])
    args.append(_rel_arg(ctx, input["context"]) if input.get("context") else ".")
    return await exec_tool(
        ctx=ctx,
        label="docker build",
        command="docker",
        args=args,
        not_found_hint="Install Docker Desktop and ensure the daemon is running.",
    )


async def _docker_run(input, ctx):
    base = resolve_workdir(ctx)
    args = ["run"]
    if input.get("rm") is not False:
        args.append("--rm")
    if input.get("detach"):
        args.append("-d")
    if input.get("name"):
        args.extend(["--name", assert_name(input["name"])])
    args.extend(port_args(input.get("ports")))
    args.extend(env_args(input.get("env")))
    for v in input.get("volumes") or []:
        args.extend(["-v", assert_safe_volume(v, base)])
    args.append(assert_image(input.get("image")))
    for c in input.get("command") or []:
        args.append(str(c))
    return await exec_tool(
        ctx=ctx,
        label="docker run",
        command="docker",
        args=args,
        not_found_hint="Install Docker Desktop and ensure the daemon is running.",
    )


async def _docker_compose(input, ctx):
    args = ["compose"]
    if input.get("file"):
        resolve_workdir(ctx, input["file"])
        args.extend(["-f", input["file"]])
    action = input.get("action")
    args.append(action)
    if action == "up":
        args.append("--abort-on-container-exit" if input.get("detach") is False else "-d")
    if action == "down":
        args.append("--remove-orphans")
    return await exec_tool(
        ctx=ctx,
        label=f"docker compose {action}",
        command="docker",
        args=args,
        dir=input.get("dir"),
        not_found_hint="Install Docker Desktop (Compose v2 ships with it).",
    )


async def _docker_info(input, ctx):
    return await exec_tool(
        ctx=ctx,
        label="docker info",
        command="docker",
        args=["version", "--format", "{{.Server.Version}}"],
        timeout_sec=30,
        not_found_hint="Install Docker Desktop; then start it so the daemon socket is available.",
    )


