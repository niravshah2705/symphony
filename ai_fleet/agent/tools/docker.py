"""Docker tools (port of agent/tools/docker.js).

Generate hardened build artifacts and drive the local Docker daemon. Everything
delegates to the ``docker`` CLI; nothing here re-implements the daemon protocol.

Security (infrastructure-misconfig checklist): generated Dockerfiles pin the
base image, run as a non-root USER, and ship a .dockerignore that keeps secrets
out of the build context. The run/build wrappers build their own argument
arrays, so ``--privileged``, ``--pid=host``, and a ``/var/run/docker.sock`` mount
are simply never expressible; secret-valued ``--build-arg``s are refused so
credentials cannot bake into image history.
"""

