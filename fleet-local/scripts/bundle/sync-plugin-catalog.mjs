#!/usr/bin/env node
// Regenerate apps/control-plane/src/bundle/packs.generated.ts from the two root
// catalogs. Run it after any change to plugin-catalog.json or skill-catalog.json:
//
//   node fleet-local/scripts/bundle/sync-plugin-catalog.mjs         # write
//   node fleet-local/scripts/bundle/sync-plugin-catalog.mjs --check # verify only
//
// The file exists because the BFF image ships only the fleet-local workspace
// (deploy/bff/Dockerfile copies fleet-local/ as its build context), so the
// catalogs under packages/shared-core are not on its filesystem at runtime. The
// catalogs stay the source of truth: --check is the gate that keeps the copy from
// going stale, and it is wired into fleet-local's test script.
//
// What is copied is deliberately narrow — the fields a bundle build needs:
// identity for the UI, the matrix cells for reachability, and the per-family
// requirement lines for the Dockerfile. promptAppend and the data-bundle image
// ride along because the apply step attaches them to the template. Digests,
// manifests, icons and the version history are not, because nothing in
// fleet-local reads them and a mirror that copies everything drifts everywhere.

import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../..');
const REGISTRY = path.join(ROOT, 'packages/shared-core/src/agent/registry');
const OUT = path.join(ROOT, 'fleet-local/apps/control-plane/src/bundle/packs.generated.ts');

const read = (file) => JSON.parse(fs.readFileSync(path.join(REGISTRY, file), 'utf8'));
const sha = (text) => createHash('sha256').update(text).digest('hex');

// Keep exactly these keys, in this order, so the output is byte-stable when the
// catalogs change in a way fleet-local does not read.
function pick(source, keys) {
  const out = {};
  for (const key of keys) if (source[key] !== undefined) out[key] = source[key];
  return out;
}

const CELL = ['status', 'engine', 'version', 'blockedOn', 'limitations'];
const REQUIREMENT = ['packages', 'dockerfile', 'dockerfileAlpine', 'writablePaths'];

function fromPlugins(catalog) {
  return catalog.plugins.map((p) => ({
    id: p.id,
    kind: 'plugin',
    label: p.label,
    version: p.bundle.version,
    dataImage: p.bundle.image,
    dataDigest: p.bundle.digest,
    requirements: pick(p.requirements, REQUIREMENT),
    cells: Object.fromEntries(Object.entries(p.harnesses).map(([cli, cell]) => [cli, pick(cell, CELL)])),
    promptAppend: p.promptAppend,
  }));
}

function fromSkills(catalog) {
  return catalog.skills.map((s) => ({
    id: s.id,
    kind: 'skill',
    label: s.label,
    version: s.artifact.version,
    dataImage: s.artifact.image,
    dataDigest: s.artifact.digest,
    requirements: pick(s.requirements, REQUIREMENT),
    cells: Object.fromEntries(Object.entries(s.harnesses).map(([cli, cell]) => [cli, pick(cell, CELL)])),
    promptAppend: s.promptAppend,
  }));
}

function render() {
  const pluginRaw = fs.readFileSync(path.join(REGISTRY, 'plugin-catalog.json'), 'utf8');
  const skillRaw = fs.readFileSync(path.join(REGISTRY, 'skill-catalog.json'), 'utf8');
  const packs = [...fromPlugins(JSON.parse(pluginRaw)), ...fromSkills(JSON.parse(skillRaw))].sort(
    (a, b) => a.id.localeCompare(b.id),
  );
  const header = [
    '// GENERATED by fleet-local/scripts/bundle/sync-plugin-catalog.mjs — do not edit.',
    `// plugin-catalog.json sha256 ${sha(pluginRaw)}`,
    `// skill-catalog.json   sha256 ${sha(skillRaw)}`,
    '// Regenerate with: node fleet-local/scripts/bundle/sync-plugin-catalog.mjs',
    '',
  ].join('\n');
  return `${header}${`export const GENERATED_AT_REVISION = ${JSON.stringify(sha(pluginRaw + skillRaw).slice(0, 12))};\n`}${`export const PACKS = ${JSON.stringify(packs, null, 2)} as const;\n`}`;
}

const check = process.argv.includes('--check');
const next = render();
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
if (check) {
  if (current !== next) {
    console.error(`packs.generated.ts is stale; run node fleet-local/scripts/bundle/sync-plugin-catalog.mjs`);
    process.exit(1);
  }
  console.log('check: packs.generated.ts is in date with both catalogs');
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, next);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${next.split('\n').length - 6} lines of data)`);
}
