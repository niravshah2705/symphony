#!/usr/bin/env node
'use strict';

/**
 * Generate the committed kagent four-CR manifests for every pack the catalogs can
 * render, from the catalogs themselves.
 *
 * Why generated rather than hand-written per pack: each manifest repeats facts
 * the catalog already owns — the pin, the version, the enabled skill list, the
 * prompt append, the runtime digest. Twelve packs times two engines is twenty-four
 * files to keep in agreement by hand, and the failure mode when they drift is an
 * agent that starts fine and runs a different skill set than the one reviewed.
 *
 * `--check` is the CI form: it renders into memory and fails on any difference,
 * so a catalog edit that should have landed in a manifest cannot pass review
 * silently.
 *
 * A file WITHOUT the generated-by header is treated as a hand-written reference
 * and never overwritten. deploy/kagent/ecc-plugin/ecc-agent.yaml (PR #307) is the
 * annotated field-by-field reference for the shape, and regenerating it would
 * trade those comments for bytes; it stays maintained by hand and is reported as
 * skipped.
 *
 * Usage:  node scripts/gen-kagent-manifests.js [--check] [--only <id>[,<id>]]
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const registry = (name) => require(path.join(ROOT, 'packages/shared-core/src/agent/registry', name));
const { CATALOG, findPlugin, validatePluginCatalog } = registry('plugin-catalog');
const { SKILLS, findSkill, validateSkillCatalog } = registry('skill-catalog');
const cr = registry('agent-crset');

const MARKER = 'GENERATED by scripts/gen-kagent-manifests.js';

const argv = process.argv.slice(2);
const CHECK = argv.includes('--check');
const onlyIndex = argv.indexOf('--only');
const ONLY = onlyIndex >= 0
  ? new Set(String(argv[onlyIndex + 1] || '').split(',').map((s) => s.trim()).filter(Boolean))
  : null;

function header(kind, id, cliKey, relPath, extra) {
  return [
    `# ${MARKER} — do not edit by hand.`,
    `# Source of truth: ${kind === 'plugin' ? 'packages/shared-core/src/agent/registry/plugin-catalog.json' : 'packages/shared-core/src/agent/registry/skill-catalog.json'}`,
    `# Regenerate: node scripts/gen-kagent-manifests.js      check drift: --check`,
    '#',
    `# ${id} on the ${cliKey} harness: ModelConfig, Harness, AgentTemplate, Agent. The`,
    '# template and the harness are paired only by the Agent below.',
    '#',
    '# For a local kind build, do not restamp this file: the builder writes',
    `# build/${id}-${cliKey}.local.yaml from it and stamps that with the registry IP.`,
    '#',
    ...extra,
    `# Apply: kubectl --context kind-kind apply -f ${relPath}`,
    '---',
    '',
  ].join('\n');
}

/** Render one (record, cliKey) pair into the text its manifest should hold. */
function render({ record, cliKey, kind, relPath }) {
  const stubbed = kind === 'plugin'
    ? cr.buildCrSet({
      plugin: record,
      cliKey,
      ociRef: record.bundle.digest ? `${record.bundle.image}@${record.bundle.digest}` : null,
    })
    : cr.buildSkillCrSet({
      skill: record,
      cliKey,
      ociRef: record.artifact.digest ? `${record.artifact.image}@${record.artifact.digest}` : null,
    });
  const version = kind === 'plugin' ? record.bundle.version : record.artifact.version;
  const commit = record.upstream.commit.slice(0, 12);
  const pin = version === commit ? `at ${commit}` : `at ${commit} (${version})`;
  const extra = [
    `# Pinned ${pin}; the oci: digest below is written back by`,
    '# .github/workflows/build-plugin-images.yml / build-skill-images.yml after the',
    '# image is published, and an unstamped placeholder is visibly all zeroes.',
  ];
  if (kind === 'plugin' && record.bundle.mcp) {
    extra.push(
      '# This bundle carries an mcp.json. Only the kagent engine reads it, so on codex',
      '# and claude the MCP servers must be bound explicitly as RemoteMCPServer tools.',
    );
  }
  return header(kind, record.id, cliKey, relPath, extra) + cr.renderCrSet(stubbed);
}

function plan() {
  const jobs = [];
  const skipped = [];
  for (const [kind, catalog, lookup] of [['plugin', CATALOG, findPlugin], ['skill', SKILLS, findSkill]]) {
    const pairs = kind === 'plugin' ? cr.renderablePairs(catalog) : cr.renderableSkillPairs(catalog);
    for (const pair of pairs) {
      const id = pair.pluginId || pair.skillId;
      if (ONLY && !ONLY.has(id)) continue;
      const record = lookup(id, catalog);
      const manifests = kind === 'plugin' ? record.bundle.manifests : record.artifact.manifests;
      const relPath = (manifests || {})[pair.cliKey];
      if (!relPath) {
        skipped.push({ id, cliKey: pair.cliKey, reason: 'the catalog row renders but names no manifest path' });
        continue;
      }
      const absolute = path.join(ROOT, relPath);
      const existing = fs.existsSync(absolute) ? fs.readFileSync(absolute, 'utf8') : null;
      if (existing && !existing.includes(MARKER)) {
        skipped.push({ id, cliKey: pair.cliKey, reason: `${relPath} is hand-written (no generated-by marker); left alone` });
        continue;
      }
      jobs.push({ kind, id, cliKey: pair.cliKey, record, relPath, absolute, text: render({ kind, record, cliKey: pair.cliKey, relPath }) });
    }
  }
  return { jobs, skipped };
}

function main() {
  const errors = [...validatePluginCatalog().errors, ...validateSkillCatalog().errors];
  if (errors.length) {
    console.error('catalog invalid; refusing to render:\n  ' + errors.join('\n  '));
    process.exitCode = 1;
    return;
  }
  const { jobs, skipped } = plan();
  const drift = [];
  for (const job of jobs) {
    const onDisk = fs.existsSync(job.absolute) ? fs.readFileSync(job.absolute, 'utf8') : null;
    if (onDisk === job.text) continue;
    drift.push(job.relPath);
    if (CHECK) continue;
    fs.mkdirSync(path.dirname(job.absolute), { recursive: true });
    fs.writeFileSync(job.absolute, job.text);
    console.log(`${onDisk === null ? 'created' : 'wrote'} ${job.relPath}`);
  }
  for (const s of skipped) console.log(`skip ${s.id}/${s.cliKey}: ${s.reason}`);
  if (CHECK && drift.length) {
    console.error(`manifests out of date with the catalogs:\n  ${drift.join('\n  ')}\n\nrun: node scripts/gen-kagent-manifests.js`);
    process.exitCode = 1;
    return;
  }
  console.log(`${CHECK ? 'check' : 'generate'}: ${jobs.length - drift.length}/${jobs.length} in date, ${drift.length} ${CHECK ? 'stale' : 'written'}, ${skipped.length} skipped`);
}

main();
